// prefetchStep is one package-manager command of the prefetch phase.
type prefetchStep struct {
	Name     string `json:"name"`
	Command  string `json:"command"`
	ExitCode int    `json:"exit_code"`
	Done     bool   `json:"done"`
}

// prefetchResult is what the prefetch microVM did, from its markers.
type prefetchResult struct {
	Ran      bool           `json:"ran"`
	TimedOut bool           `json:"timed_out"`
	Steps    []prefetchStep `json:"steps"`
	Fetched  []fetchCount   `json:"fetched"`
	Refused  []string       `json:"refused"`
	Findings []finding      `json:"findings"`
}

type fetchCount struct {
	Target string `json:"target"`
	Count  int    `json:"count"`
}

// planPrefetch lists the downloads a skill needs before it can run: npm
// dependencies (unless node_modules is bundled), wheels for each
// requirements file, and the packages MCP servers launch with npx or uvx.
func planPrefetch(dir string, eps []entryPoint) []prefetchStep {
	var steps []prefetchStep
	if hasNPMDependencies(dir) {
		install := "npm install"
		for _, lock := range []string{"package-lock.json", "npm-shrinkwrap.json"} {
			if _, err := os.Stat(filepath.Join(dir, lock)); err == nil {
				install = "npm ci"
			}
		}
		steps = append(steps, prefetchStep{Name: "npm", Command: install + " && cp -a node_modules /mnt/"})
	}
	reqs, _ := filepath.Glob(filepath.Join(dir, "requirements*.txt")) // pattern is valid
	for _, r := range reqs {
		name := filepath.Base(r)
		steps = append(steps, prefetchStep{
			Name:    "pip:" + name,
			Command: shellJoin([]string{"pip", "download", "--only-binary=:all:", "-d", "/mnt/wheels", "-r", name}),
		})
	}
	for _, ep := range eps {
		switch {
		case ep.Package == "":
		case ep.Runner == "npx":
			steps = append(steps, prefetchStep{
				Name:    "npx:" + ep.Package,
				Command: shellJoin([]string{"npm", "exec", "--yes", "--package=" + ep.Package, "--", "true"}),
			})
		case ep.Runner == "uvx":
			steps = append(steps, prefetchStep{
				Name:    "uvx:" + ep.Package,
				Command: shellJoin([]string{"uv", "tool", "install", ep.Package}),
			})
		}
	}
	return steps
}

// prefetchScript runs the steps as the runner, with package-manager scripts
// and source builds disabled, through the relay to the registry-only proxy.
func prefetchScript(steps []prefetchStep) string {
	var b strings.Builder
	b.WriteString(`#!/bin/sh
# Generated by sbox scan; runs as root in the prefetch microVM. $nonce comes from the init.
proxy=http://172.16.0.1:3128
step() { # name, command
	echo "SBOX-$nonce STEP $1"
	setpriv --reuid=runner --regid=runner --init-groups env -i HOME=/home/runner USER=runner PATH=/usr/local/bin:/usr/bin:/bin \
		HTTPS_PROXY=$proxy HTTP_PROXY=$proxy https_proxy=$proxy http_proxy=$proxy \
		npm_config_cache=/mnt/npm-cache npm_config_ignore_scripts=true npm_config_audit=false \
		npm_config_fund=false npm_config_update_notifier=false \
		UV_CACHE_DIR=/mnt/uv-cache UV_NO_BUILD=1 UV_PYTHON_DOWNLOADS=never \
		PIP_ONLY_BINARY=:all: PIP_DISABLE_PIP_VERSION_CHECK=1 \
		sh -c "$2" >/tmp/step.log 2>&1
	status=$?
	tail -n 15 /tmp/step.log
	echo
	echo "SBOX-$nonce STEP-RESULT $1 $status"
}
`)
	for _, s := range steps {
		fmt.Fprintf(&b, "step %s %s\n", shellJoin([]string{s.Name}), shellJoin([]string{s.Command}))
	}
	return b.String()
}

// collectPrefetch reads the prefetch markers: the guest's step results and
// the proxy log sbox-run prints after the prefetch microVM exits.
func collectPrefetch(steps []prefetchStep, markers []string) *prefetchResult {
	res := &prefetchResult{Steps: steps, Fetched: []fetchCount{}, Refused: []string{}}
	counts := make(map[string]int)
	for _, m := range markers {
		kind, rest, _ := strings.Cut(m, " ")
		switch kind {
		case "PREFETCH-BEGIN":
			res.Ran = true
		case "PREFETCH-TIMEOUT":
			res.TimedOut = true
		case "STEP-RESULT":
			name, code, _ := strings.Cut(rest, " ")
			for i := range res.Steps {
				if res.Steps[i].Name == name {
					res.Steps[i].Done = true
					res.Steps[i].ExitCode, _ = strconv.Atoi(code)
				}
			}
		case "FETCH":
			verdict, target, _ := strings.Cut(rest, " ")
			switch verdict {
			case "ALLOW":
				if counts[target] == 0 {
					res.Fetched = append(res.Fetched, fetchCount{Target: target})
				}
				counts[target]++
			case "DENY":
				if !slices.Contains(res.Refused, target) {
					res.Refused = append(res.Refused, target)
				}
			}
		}
	}
	for i := range res.Fetched {
		res.Fetched[i].Count = counts[res.Fetched[i].Target]
	}

	for _, target := range res.Refused {
		res.Findings = append(res.Findings, finding{
			Severity: sevMedium, Rule: "prefetch-refused",
			Detail: "a dependency fetch outside the package registries was refused: " + target,
		})
	}
	for _, s := range res.Steps {
		if s.Done && s.ExitCode != 0 {
			res.Findings = append(res.Findings, finding{
				Severity: sevLow, Rule: "prefetch-failed",
				Detail: fmt.Sprintf("%s failed (exit %d): entry points run without it", s.Name, s.ExitCode),
			})
		}
	}
	if res.TimedOut {
		res.Findings = append(res.Findings, finding{Severity: sevLow, Rule: "prefetch-timeout", Detail: "the prefetch timed out"})
	}
	return res
}

func writePrefetchReport(b *strings.Builder, res *prefetchResult) {
	b.WriteString("\ndependencies (prefetched through a registry-only proxy)\n")
	if !res.Ran {
		b.WriteString("     the prefetch microVM did not start\n")
	}
	for _, s := range res.Steps {
		status := "did not run"
		switch {
		case s.Done && s.ExitCode == 0:
			status = "ok"
		case s.Done:
			status = fmt.Sprintf("exit %d", s.ExitCode)
		}
		fmt.Fprintf(b, "     %-10s %-28s %s\n", "", printable(s.Name), status)
	}
	fetched := make([]string, len(res.Fetched))
	for i, f := range res.Fetched {
		fetched[i] = fmt.Sprintf("%s ×%d", f.Target, f.Count)
	}
	writeList(b, "fetched", fetched)
	if len(res.Refused) > 0 {
		writeList(b, "refused", res.Refused)
	}
	writeFindings(b, res.Findings)
}

// hasNPMDependencies reports whether the root package.json declares
// dependencies that aren't already bundled in node_modules.
func hasNPMDependencies(dir string) bool {
	if _, err := os.Stat(filepath.Join(dir, "node_modules")); err == nil {
		return false
	}
	data, err := os.ReadFile(filepath.Join(dir, "package.json"))
	if err != nil {
		return false
	}
	var pkg struct {
		Dependencies         map[string]string
		OptionalDependencies map[string]string
	}
	return json.Unmarshal(data, &pkg) == nil && len(pkg.Dependencies)+len(pkg.OptionalDependencies) > 0
}

// runnerPackage finds the package an npx or uvx command launches.
func runnerPackage(cmd string, args []string) (runner, pkg string) {
	runner = path.Base(cmd)
	if runner != "npx" && runner != "uvx" {
		return "", ""
	}
	for i := 0; i < len(args); i++ {
		a := args[i]
		switch {
		case a == "--from" || a == "--package" || a == "-p":
			if i+1 < len(args) {
				return runner, args[i+1]
			}
		case strings.HasPrefix(a, "--package="):
			return runner, strings.TrimPrefix(a, "--package=")
		case strings.HasPrefix(a, "-"):
		default:
			return runner, a
		}
	}
	return runner, ""
}
